#!/usr/bin/env python3
"""Writes hud/layout/at_ui.xml: the Auto Tournament clickable HUD (buttons, v2).

One block set, drawn three times: `ui_card` (right, above the weapons), `ui_mid` (centre of the
lower half) and `ui_left` (menus: a list on the left, rows chosen with W S and held with E). The server fills fixed slots, so new screens need no addon update:

  text      <p>_kind <p>_title <p>_sub <p>_timer <p>_counter <p>_hint     ({s:text}, has-* classes)
  teams     <p>_tA <p>_tB, dots <p>_dA0..4 <p>_dB0..4 (class on)          (has-teams)
  confirm   <p>_c0..1 with _team / _state (class ready)                    (has-confirm)
  chips     <p>_k0..2 with _l label / _c command                           (has-cmds)
  rows      <p>_n0..4 with _k label / _v value (class gone; cmd boxes v)  (has-lines)
  buttons   <p>_b0..7 with _l label / _s count; classes show, t-<tone>, picked, off
            row classes on the panel: cols-1..4, bw-s / bw-m / bw-l / bw-xl (has-buttons)
  close     <p>_close with _l                                              (has-close)

<p> is ui_card, ui_mid or ui_left (rows: class sel on the chosen one, hold while E is down). Panel classes: on, c-live / c-warn / c-ban / c-muted (accent default),
mini (the card as a one-line pill), fx-<enter>, leaving + out-<exit>, urgent (5 s or less on the
timer), and any utility from the spec's cls= (at_ui.css, "Tailwind for CS2"). Parts with ids take
cls.<part>= utilities: _brand _kind _title _sub _hint _timer _counter _teams _confirm _lines _cmds
_buttons _close _flow _b0.._b7. Buttons: pulse (the one waiting). Counter / kind: bump (briefly).
Button ids are what CS_UM_CustomHudClicked carries back. Run after changing the structure:
python hud/tools/gen_ui.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "hud" / "layout" / "at_ui.xml"
CSS = ROOT / "hud" / "styles" / "at_ui.css"
# The addon version (bump it every publish): plugins/hud/hud_addon.h.
VERSION = int(re.search(r"kAddonVersion = (\d+);", (ROOT / "plugins" / "hud" / "hud_addon.h").read_text(encoding="utf-8")).group(1))
VER_BEGIN = "/* addon version (generated by hud/tools/gen_ui.py from plugins/hud/hud_addon.h) */"
VER_END = "/* end addon version */"


def label(id_=None, cls="", text="{s:text}"):
    i = f' id="{id_}"' if id_ else ""
    return f'<Label{i} class="{cls}" text="{text}" hittest="false" />'


def panel(id_=None, cls="", children="", hit=False):
    i = f' id="{id_}"' if id_ else ""
    h = "true" if hit else "false"
    if not children:
        return f'<Panel{i} class="{cls}" hittest="{h}" />'
    return f'<Panel{i} class="{cls}" hittest="{h}">{children}</Panel>'


def button(id_, cls, children):
    return f'<Button id="{id_}" class="{cls}">{children}</Button>'


def block(p):
    brand = panel(f"{p}_brand", "ui-brand", children=panel(cls="ui-logo") + label(cls="ui-brandname", text="AUTO TOURNAMENT"))
    teams = panel(f"{p}_teams", "ui-teams", children="".join(
        panel(cls="ui-team", children=label(f"{p}_t{t}", "ui-teamname") + "".join(panel(f"{p}_d{t}{n}", "ui-dot") for n in range(5)))
        for t in "AB"))
    confirm = panel(f"{p}_confirm", "ui-confirm", children="".join(
        panel(f"{p}_c{n}", "ui-chipbox", label(f"{p}_c{n}_team", "ui-chipteam") + label(f"{p}_c{n}_state", "ui-chipstate"))
        for n in range(2)))
    vs = panel(f"{p}_vs", "ui-vs", children=label(f"{p}_vsA", "ui-vsname") + label(cls="ui-vsmid", text="vs")
               + label(f"{p}_vsB", "ui-vsname"))
    cmds = panel(f"{p}_cmds", "ui-cmds", children="".join(
        panel(f"{p}_k{n}", "ui-cmd", label(f"{p}_k{n}_l", "ui-cmdlabel") + panel(cls="ui-kbd", children=label(f"{p}_k{n}_c", "ui-kbdtext")))
        for n in range(3)))
    rows = panel(f"{p}_lines", "ui-lines", children="".join(
        panel(f"{p}_n{n}", "ui-row", label(f"{p}_n{n}_k", "ui-rowk") + label(f"{p}_n{n}_v", "ui-rowv"))
        for n in range(5)))
    # The first button can be held with Use (hud.so puts `holdable` on it, then `hold` while the key
    # is down): a fill behind the label and the player's own key ({g:csgo_key:k}) at its left.
    def hold_parts(n):
        if p == "ui_left":
            # The menu panel: every row can be chosen (W S) and held (E): a mark bar at its left
            # and the slide fill behind the label.
            return panel(cls="ui-rowmark") + panel(cls="ui-btnfill")
        if n:
            return ""
        return panel(cls="ui-btnfill") + panel(cls="ui-btnkey", children=(
            panel(cls="ui-kcbr ui-kcl") + panel(cls="ui-kcbr ui-kcr") + label(f"{p}_b0_k", "ui-kct", "{g:csgo_key:k}")))
    buttons = panel(f"{p}_buttons", "ui-buttons", children="".join(
        button(f"{p}_b{n}", "ui-btn", panel(cls="ui-btnglow") + hold_parts(n) + label(f"{p}_b{n}_l", "ui-btnlabel") + label(f"{p}_b{n}_s", "ui-btnsub"))
        for n in range(24)))
    close_parts = panel(cls="ui-rowmark") + panel(cls="ui-btnfill") if p == "ui_left" else ""
    close = button(f"{p}_close", "ui-close", close_parts + label(f"{p}_close_l", "ui-closelabel"))
    # Behind the content: a wash of the accent from the left and a few breathing pixels (cs2-ui-kit).
    # ui-back doubles the panel background: CS2 draws one layer of it see-through (2026-10-27).
    back = panel(cls="ui-back") + panel(cls="ui-wash") + panel(cls="ui-pixels", children="".join(
        panel(cls=f"ui-px p{n} px-{'abcd'[n % 4]}") for n in range(8)))
    flow = panel(f"{p}_flow", "ui-flow", children=(
        brand + label(f"{p}_kind", "ui-kind") + label(f"{p}_title", "ui-title") + label(f"{p}_sub", "ui-sub") + vs
        + teams + confirm + rows + buttons + cmds + close + label(f"{p}_hint", "ui-hint")))
    extras = label(f"{p}_timer", "ui-timer") + label(f"{p}_counter", "ui-counter") + panel(cls="ui-line") + panel(cls="ui-flash")
    return panel(p, f"ui-panel ui-{p[3:]}", back + flow + extras, hit=True)


def main():
    # The wraps carry the HUD scale (scale-70 .. scale-100, set by hud.so: `ru hudkit scale`).
    body = panel("ui_cardwrap", "ui-cardwrap", block("ui_card")) + panel("ui_midwrap", "ui-midwrap", block("ui_mid"))
    # Menus: a list on the left, vertically centred (v4, Hold E). W S move the `sel` row (hud.so),
    # holding E slides the fill across it, the close row is always last.
    body += panel("ui_leftwrap", "ui-leftwrap", block("ui_left"))
    # "Your HUD addon is out of date": shown unless hud.so's v-<n> class is one this addon knows.
    body += panel("ui_ver", "ui-ver", label("ui_ver_t", "ui-vertext"))
    # Hold Use: a chip top right that names the key the player bound to +use ({g:csgo_key:k}, k set
    # to "+use" by hud.so) and what holding it does. hud.so puts `hold` on it while the key is down,
    # which runs the fill; at the end it presses the open card's button or opens .menu.
    keycap = panel(cls="ui-kc", children=(
        panel(cls="ui-kcbr ui-kcl") + panel(cls="ui-kcbr ui-kcr") + label("ui_hold_k", "ui-kct", "{g:csgo_key:k}")))
    body += panel("ui_hold", "ui-hold", (
        panel(cls="ui-holdbg") + panel(cls="ui-holdfill")
        + panel(cls="ui-holdbody", children=keycap + label("ui_hold_t", "ui-holdt"))))
    xml = f"""<!--
  Auto Tournament clickable HUD (generated by hud/tools/gen_ui.py: edit that, then run it).
  Design: https://claude.ai/artifact/Nnt5WzmHAQbt8bXpoYKv97 (page Buttons (v2))
  m_strLayout = "panorama/layout/custom_game/at_ui.xml"
-->
<root>
	<styles>
		<include src="s2r://panorama/styles/custom_game/at_ui.vcss_c" />
	</styles>
	<Panel class="ui-root" hittest="false">{body}</Panel>
</root>
"""
    OUT.write_text(xml.replace("><", ">\n<"), encoding="utf-8")
    print(f"wrote {OUT}")
    write_version_css()


def write_version_css():
    # This addon knows its own version and every older one: a server still on an older version
    # must not tell a player with a newer addon to update.
    rules = "\n".join(f".ui-ver.check.v-{n} {{ visibility: collapse; }}" for n in range(1, VERSION + 1))
    block = f"{VER_BEGIN}\n{rules}\n{VER_END}"
    css = CSS.read_text(encoding="utf-8")
    start, end = css.find(VER_BEGIN), css.find(VER_END)
    if start < 0 or end < 0:
        raise SystemExit(f"{CSS}: the addon version markers are missing")
    CSS.write_text(css[:start] + block + css[end + len(VER_END):], encoding="utf-8")
    print(f"wrote {CSS} (addon version {VERSION})")


if __name__ == "__main__":
    main()
