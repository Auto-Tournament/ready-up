#!/usr/bin/env python3
"""Writes hud/layout/at_ui.xml: the Auto Tournament clickable HUD (buttons, v2).

One block set, drawn twice: `ui_card` (right, above the weapons) and `ui_mid` (centre of the lower
half). The server fills fixed slots, so new screens need no addon update:

  text      <p>_kind <p>_title <p>_sub <p>_timer <p>_counter <p>_hint     ({s:text}, has-* classes)
  teams     <p>_tA <p>_tB, dots <p>_dA0..4 <p>_dB0..4 (class on)          (has-teams)
  confirm   <p>_c0..1 with _team / _state (class ready)                    (has-confirm)
  chips     <p>_k0..2 with _l label / _c command                           (has-cmds)
  rows      <p>_n0..4 with _k label / _v value (class gone; cmd boxes v)  (has-lines)
  buttons   <p>_b0..7 with _l label / _s count; classes show, t-<tone>, picked, off
            row classes on the panel: cols-1..4, bw-s / bw-m / bw-l / bw-xl (has-buttons)
  close     <p>_close with _l                                              (has-close)

<p> is ui_card or ui_mid. Panel classes: on, c-live / c-warn / c-ban / c-muted (accent default),
mini (the card as a one-line pill), fx-open / fx-flip / fx-alert (how the centre panel enters),
urgent (5 s or less on the timer). Buttons: pulse (the one waiting). Counter / kind: bump (briefly).
Button ids are what CS_UM_CustomHudClicked carries back. Run after changing the structure:
python hud/tools/gen_ui.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "layout" / "at_ui.xml"


def label(id_=None, cls="", text="{s:text}"):
    i = f' id="{id_}"' if id_ else ""
    return f'<Label{i} class="{cls}" text="{text}" hittest="false" />'


def panel(id_=None, cls="", children="", hit=False):
    i = f' id="{id_}"' if id_ else ""
    h = "true" if hit else "false"
    if not children:
        return f'<Panel{i} class="{cls}" hittest="{h}" />'
    return f'<Panel{i} class="{cls}" hittest="{h}">{children}</Panel>'


def button(id_, cls, children):
    return f'<Button id="{id_}" class="{cls}">{children}</Button>'


def block(p):
    brand = panel(cls="ui-brand", children=panel(cls="ui-logo") + label(cls="ui-brandname", text="AUTO TOURNAMENT"))
    teams = panel(cls="ui-teams", children="".join(
        panel(cls="ui-team", children=label(f"{p}_t{t}", "ui-teamname") + "".join(panel(f"{p}_d{t}{n}", "ui-dot") for n in range(5)))
        for t in "AB"))
    confirm = panel(cls="ui-confirm", children="".join(
        panel(f"{p}_c{n}", "ui-chipbox", label(f"{p}_c{n}_team", "ui-chipteam") + label(f"{p}_c{n}_state", "ui-chipstate"))
        for n in range(2)))
    cmds = panel(cls="ui-cmds", children="".join(
        panel(f"{p}_k{n}", "ui-cmd", label(f"{p}_k{n}_l", "ui-cmdlabel") + panel(cls="ui-kbd", children=label(f"{p}_k{n}_c", "ui-kbdtext")))
        for n in range(3)))
    rows = panel(cls="ui-lines", children="".join(
        panel(f"{p}_n{n}", "ui-row", label(f"{p}_n{n}_k", "ui-rowk") + label(f"{p}_n{n}_v", "ui-rowv"))
        for n in range(5)))
    buttons = panel(cls="ui-buttons", children="".join(
        button(f"{p}_b{n}", "ui-btn", panel(cls="ui-btnglow") + label(f"{p}_b{n}_l", "ui-btnlabel") + label(f"{p}_b{n}_s", "ui-btnsub"))
        for n in range(8)))
    close = button(f"{p}_close", "ui-close", label(f"{p}_close_l", "ui-closelabel"))
    # Behind the content: a wash of the accent from the left and a few breathing pixels (cs2-ui-kit).
    back = panel(cls="ui-wash") + panel(cls="ui-pixels", children="".join(
        panel(cls=f"ui-px p{n} px-{'abcd'[n % 4]}") for n in range(8)))
    flow = panel(cls="ui-flow", children=(
        brand + label(f"{p}_kind", "ui-kind") + label(f"{p}_title", "ui-title") + label(f"{p}_sub", "ui-sub")
        + teams + confirm + rows + cmds + buttons + close + label(f"{p}_hint", "ui-hint")))
    extras = label(f"{p}_timer", "ui-timer") + label(f"{p}_counter", "ui-counter") + panel(cls="ui-line") + panel(cls="ui-flash")
    return panel(p, f"ui-panel ui-{p[3:]}", back + flow + extras, hit=True)


def main():
    body = panel(cls="ui-cardwrap", children=block("ui_card")) + panel(cls="ui-midwrap", children=block("ui_mid"))
    xml = f"""<!--
  Auto Tournament clickable HUD (generated by hud/tools/gen_ui.py: edit that, then run it).
  Design: https://claude.ai/artifact/Nnt5WzmHAQbt8bXpoYKv97 (page Buttons (v2))
  m_strLayout = "panorama/layout/custom_game/at_ui.xml"
-->
<root>
	<styles>
		<include src="s2r://panorama/styles/custom_game/at_ui.vcss_c" />
	</styles>
	<Panel class="ui-root" hittest="false">{body}</Panel>
</root>
"""
    OUT.write_text(xml.replace("><", ">\n<"), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
