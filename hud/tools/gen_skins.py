"""Writes hud/styles/at_skins.css: one class per CS2 skin picture, for tiles in the HUD (at_ui).

    python hud/tools/gen_skins.py "D:/SteamLibrary/steamapps/common/Counter-Strike Global Offensive"

The pictures are the game's own (panorama/images/econ/default_generated/<name>.vtex, every finish
in its light, medium and heavy wear look). The names come from the game's pak01_dir.vpk.

A HUD utility class is at most 32 characters of [a-z0-9-] (hud_screen.cpp UtilityName), so each
picture's class is `sk-` and the FNV-1a 32-bit hash of its name in 8 hex digits. The skins plugin
computes the same (plugins/skins/inventory.cpp SkinPictureClass) from the name the platform sends
(skins.inventory items[].image). Run it again after a CS2 update with new skins, then publish.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "hud" / "styles" / "at_skins.css"
NAME = re.compile(rb"[a-z0-9_-]{3,120}_(?:light|medium|heavy)_png(?=\x00)")


def fnv1a32(s: str) -> str:
    h = 0x811C9DC5
    for b in s.encode("ascii"):
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}"


def picture_class(name: str) -> str:
    return "sk-" + fnv1a32(name)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    vpk = Path(sys.argv[1]) / "game" / "csgo" / "pak01_dir.vpk"
    data = vpk.read_bytes()
    if b"panorama/images/econ/default_generated" not in data:
        raise SystemExit(f"{vpk}: no econ/default_generated folder")
    # The VPK tree stores each file name once; skin pictures are the only *_light|medium|heavy_png.
    names = sorted({m.group(0).decode() for m in NAME.finditer(data)})
    if len(names) < 1000:
        raise SystemExit(f"{vpk}: only {len(names)} skin pictures found; the VPK layout changed?")
    seen = {}
    rules = []
    for n in names:
        c = picture_class(n)
        if c in seen:
            raise SystemExit(f"hash clash: {n} and {seen[c]}")
        seen[c] = n
        rules.append(f'.{c} {{ background-image: url( "s2r://panorama/images/econ/default_generated/{n}.vtex" ); }}')
    head = (
        "/* Generated by hud/tools/gen_skins.py from the game's file index: edit that, not this.\n"
        "   One class per CS2 skin picture (`sk-` + FNV-1a 32 of its name), for tiles (`btn=…|img`)\n"
        "   and the large picture (`img=`) in at_ui. */\n"
    )
    OUT.write_text(head + "\n".join(rules) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(rules)} pictures")


if __name__ == "__main__":
    main()
